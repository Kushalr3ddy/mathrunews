/* ---- language state (persisted) ---- */
const LangStore = {
  key: "msm-lang",
  get() {
    try { return localStorage.getItem(this.key) || "en"; } catch (e) { return "en"; }
  },
  set(v) {
    try { localStorage.setItem(this.key, v); } catch (e) {}
  }
};

function currentLang() {
  const l = LangStore.get();
  return (l === "kn") ? "kn" : "en";
}
function t(key) {
  const lang = currentLang();
  return (I18N[lang] && I18N[lang][key] != null) ? I18N[lang][key] : (I18N.en[key] || key);
}
